export const getDestinationById = (id) => DESTINATIONS.find(d => d.id === id);

// Country / Location-aware sorting helper
export const filterDestinations = (search, category, userCountryName = '') => {
  let list = DESTINATIONS.filter(dest => {
    const matchSearch = !search ||
      dest.name.toLowerCase().includes(search.toLowerCase()) ||
      dest.country.toLowerCase().includes(search.toLowerCase()) ||
      dest.tagline.toLowerCase().includes(search.toLowerCase());

    const matchCategory = category === 'All' || dest.category.includes(category);

    return matchSearch && matchCategory;
  });

  // Sort by user's country matching first if user country is known
  if (userCountryName && !search) {
    const cLower = userCountryName.toLowerCase();
    list = [...list].sort((a, b) => {
      const aMatch = a.country.toLowerCase().includes(cLower) || (cLower.includes('india') && a.country === 'India');
      const bMatch = b.country.toLowerCase().includes(cLower) || (cLower.includes('india') && b.country === 'India');
      if (aMatch && !bMatch) return -1;
      if (!aMatch && bMatch) return 1;
      return 0;
    });
  }

  return list;
};
